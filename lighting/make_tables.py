"""Markdown tables for the lighting section, generated from runs/lighting/*.json.

Writes lighting/results.md. Nothing is typed by hand: every cell is read back
from the sweep output, so the table cannot drift away from the run that
produced it. Recall and stage accuracy are reported at conf 0.25, counting MAE
at the best threshold per level, for the reason given in run_lighting.py's
docstring - a change of exposure moves confidences wholesale, so a fixed
threshold would compare calibration rather than models.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIGHT = ROOT / "runs" / "lighting"
OUT = Path(__file__).resolve().parent / "results.md"

MODELS = [
    ("n", "YOLO11n (stock HSV)", None),
    ("light_no_colour", "n, no colour jitter", "light_no_colour"),
    ("light_hsv_v08", "n, hsv_v08 (brightness x2)", "light_hsv_v08"),
    ("light_hsv_wide", "n, hsv_wide (+ hue)", "light_hsv_wide"),
    ("s", "YOLO11s", "laboro_yolo11s_exiffix_b16_mps"),
    ("m", "YOLO11m", "laboro_yolo11m_exiffix_b8_mps"),
    ("l", "YOLO11l", "laboro_yolo11l_exiffix_b8_mps"),
    ("x", "YOLO11x", "laboro_yolo11x_exiffix_b4_mps"),
]
N_MAP50_95 = 0.706  # reproduce repo run; see runtime_bench/model_size_results.md


def load(model: str) -> dict:
    data = json.load(open(LIGHT / f"{model}.json"))
    rows = {}
    for axis, knob in (("exposure", "stops"), ("white_balance", "wb")):
        for row in data["axes"][axis]:
            rows[(knob, round(row["value"], 2))] = row
    return rows


def clean_map(run: str | None) -> float:
    if run is None:
        return N_MAP50_95
    csv_rows = list(csv.DictReader(open(ROOT / "runs" / run / "results.csv")))
    key = next(k for k in csv_rows[0] if "mAP50-95" in k)
    return max(float(r[key]) for r in csv_rows)


def table(header: list[str], body: list[list[str]]) -> str:
    align = ["---"] + ["---:"] * (len(header) - 1)
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join(align) + " |"]
    lines += ["| " + " | ".join(row) + " |" for row in body]
    return "\n".join(lines)


def main() -> None:
    data = {short: load(short) for short, _, _ in MODELS}

    exposure = [-3.0, -2.0, -1.5, -1.0, -0.5, 0.0, 0.5, 1.0, 1.5, 2.0, 3.0]
    wb = [-1.5, -1.0, -0.66, -0.33, 0.0, 0.33, 0.66, 1.0, 1.5]
    extremes = [("stops", -3.0), ("stops", 0.0), ("stops", 3.0), ("wb", -1.5), ("wb", 1.5)]

    parts = [
        "# Lighting results",
        "",
        "Generated by `python lighting/make_tables.py` from `runs/lighting/*.json`",
        "(the sweeps of `lighting/run_lighting.py`) and the training `results.csv`",
        "of each run. Do not edit by hand.",
        "",
        "161 Laboro validation images, six-class protocol, labels untouched; one",
        "photometric knob per level (`lighting/relight.py`), applied in linear light.",
        "Recall is class-agnostic at IoU 0.5 and conf 0.25, stage accuracy is measured",
        "among found fruit, counting MAE is per image at the best threshold of that",
        "level. One seed per row: treat differences under ~0.02 recall as noise.",
        "",
        "Figures: `paper/figures/lighting_sizes.png`, `lighting_hsv.png`, and the",
        "example strip `lighting_examples.jpg` (`paper/make_size_lighting_figures.py`).",
        "",
        "## Headline: clean frame against the four extremes",
        "",
        "Each cell is recall at conf 0.25 / counting MAE at the best threshold.",
        "",
    ]

    header = ["Model", "clean mAP50-95", "clean", "-3 stops", "+3 stops",
              "wb -1.5 (cool)", "wb +1.5 (warm)"]
    body = []
    for short, label, run in MODELS:
        row = [label, f"{clean_map(run):.3f}"]
        for knob, value in [("stops", 0.0)] + [e for e in extremes if e != ("stops", 0.0)]:
            cell = data[short][(knob, round(value, 2))]
            row.append(f"{cell['by_conf']['0.25']['recall']:.3f} / {cell['best_counting_mae']:.2f}")
        body.append(row)
    parts += [table(header, body), ""]

    parts += ["## Stage accuracy among found fruit (conf 0.25)", ""]
    header = ["Model", "clean", "-3 stops", "+3 stops", "wb -1.5", "wb +1.5"]
    body = []
    for short, label, _ in MODELS:
        row = [label]
        for knob, value in [("stops", 0.0)] + [e for e in extremes if e != ("stops", 0.0)]:
            row.append(f"{data[short][(knob, round(value, 2))]['stage_accuracy']:.3f}")
        body.append(row)
    parts += [table(header, body), ""]

    for title, knob, levels, fmt in (
        ("Full exposure sweep", "stops", exposure, lambda v: f"{v:+.1f}"),
        ("Full white-balance sweep", "wb", wb, lambda v: f"{v:+.2f}"),
    ):
        for metric, name, get in (
            ("recall", "recall at conf 0.25", lambda r: f"{r['by_conf']['0.25']['recall']:.3f}"),
            ("mae", "counting MAE at the best threshold",
             lambda r: f"{r['best_counting_mae']:.2f}"),
        ):
            parts += [f"## {title}: {name}", ""]
            header = ["Model"] + [fmt(v) for v in levels]
            body = []
            for short, label, _ in MODELS:
                body.append([label] + [get(data[short][(knob, round(v, 2))]) for v in levels])
            parts += [table(header, body), ""]
            if metric == "recall" and knob == "stops":
                luma = [data["n"][(knob, round(v, 2))]["mean_luma"] for v in levels]
                parts += ["Mean luma of the val split at each level: "
                          + ", ".join(f"{fmt(v)} -> {m:.0f}" for v, m in zip(levels, luma))
                          + ".", ""]

    OUT.write_text("\n".join(parts) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
