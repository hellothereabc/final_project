"""Markdown tables for the size ladder and the laptop-vs-phone comparison.

Writes runtime_bench/device_tables.md from the saved measurements only:

  runs/runtime/mac_model_sizes.json               mac_sanity.py, Mac16,8
  phone_iPhone18-1_ios27_yolo11*_laboro.json      phone_bench.sh, iOS 27.0
  phone_iPhone18-1_ios27_yolo11{l,x}_sustained.json, phone_iPhone18-1_yolo11m_sustained.json
  runs/laboro_model_size_thresholds_nsmlx.json    size_thresholds.py
  runs/laboro_yolo11*_exiffix_*_mps/results.csv   training mAP50-95

The prose reading of these numbers is model_size_results.md; this file is the
generated companion so a table can be regenerated rather than retyped.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BENCH = Path(__file__).resolve().parent
OUT = BENCH / "device_tables.md"

SIZES = ["n", "s", "m", "l", "x"]
RUN_DIRS = {
    "s": "laboro_yolo11s_exiffix_b16_mps",
    "m": "laboro_yolo11m_exiffix_b8_mps",
    "l": "laboro_yolo11l_exiffix_b8_mps",
    "x": "laboro_yolo11x_exiffix_b4_mps",
}
N_MAP50_95 = 0.706  # reproduce repo run, see model_size_results.md
BUDGET_MS = 1000.0 / 30.0


def mac() -> dict:
    rows = json.load(open(ROOT / "runs" / "runtime" / "mac_model_sizes.json"))["rows"]
    out: dict[str, dict] = {}
    for row in rows:
        size = row["model"].replace("YOLO11", "")
        out.setdefault(size, {})["cpu" if row["units"] == "CPU_ONLY" else "ne"] = row
    return out


def phone() -> dict:
    out: dict[str, dict] = {}
    for size in SIZES:
        report = json.load(open(BENCH / f"phone_iPhone18-1_ios27_yolo11{size}_laboro.json"))
        entry = {"os": report.get("os", "")}
        for cfg in report["configs"]:
            entry["cpu" if cfg["computeUnits"] == "cpuOnly" else "ne"] = cfg
        path = BENCH / f"phone_iPhone18-1_ios27_yolo11{size}_sustained.json"
        if size == "m":  # only measured on iOS 26.5.2, 14 September
            path = BENCH / "phone_iPhone18-1_yolo11m_sustained.json"
        if path.exists():
            report = json.load(open(path))
            entry["sustained"] = report["configs"][0]
            entry["sustained_os"] = report.get("os", "")
        out[size] = entry
    return out


def accuracy() -> dict:
    sweep = json.load(open(ROOT / "runs" / "laboro_model_size_thresholds_nsmlx.json"))["rows"]
    out = {}
    for size in SIZES:
        rows = [r for r in sweep if r["model"] == f"YOLO11{size}"]
        best_all = min(rows, key=lambda r: r["counting_mae"])
        best_ripe = min(rows, key=lambda r: r["ripe_mae"])
        if size == "n":
            score = N_MAP50_95
        else:
            csv_rows = list(csv.DictReader(open(ROOT / "runs" / RUN_DIRS[size] / "results.csv")))
            key = next(k for k in csv_rows[0] if "mAP50-95" in k)
            score = max(float(r[key]) for r in csv_rows)
        out[size] = {
            "map": score,
            "mae": best_all["counting_mae"], "mae_conf": best_all["conf"],
            "ripe": best_ripe["ripe_mae"], "ripe_conf": best_ripe["conf"],
        }
    return out


def table(header, body) -> str:
    align = ["---"] + ["---:"] * (len(header) - 1)
    return "\n".join(
        ["| " + " | ".join(header) + " |", "| " + " | ".join(align) + " |"]
        + ["| " + " | ".join(row) + " |" for row in body]
    )


def main() -> None:
    m, p, acc = mac(), phone(), accuracy()

    parts = [
        "# Size ladder and device tables",
        "",
        "Generated by `python runtime_bench/make_device_tables.py`. Do not edit by hand;",
        "the reading of these numbers is in `model_size_results.md`.",
        "",
        "Inference-only Core ML measurements, FP16 exports with embedded NMS, the same",
        "three bundled images, 10 repeats after warm-up. They exclude camera capture,",
        "display, and app rendering. Mac is a Mac16,8; the phone is an iPhone 17 Pro",
        f"(`iPhone18,1`) on {p['n']['os']}. Accuracy is the 161-image Laboro val split,",
        "one seed per model.",
        "",
        "Figures: `paper/figures/size_accuracy.png`, `device_latency.png`,",
        "`accuracy_vs_latency.png` (`paper/make_size_lighting_figures.py`).",
        "",
        "## Accuracy and cost",
        "",
    ]
    body = [[
        f"YOLO11{s}",
        f"{acc[s]['map']:.3f}",
        f"{acc[s]['mae']:.3f} at {acc[s]['mae_conf']:.2f}",
        f"{acc[s]['ripe']:.3f} at {acc[s]['ripe_conf']:.2f}",
        f"{m[s]['ne']['package_mb']:.1f} MB",
        f"{p[s]['ne']['load_ms'] / 1000:.2f} s",
    ] for s in SIZES]
    parts += [table(["Model", "mAP50-95", "Best counting MAE", "Best fully-ripe MAE",
                     "Core ML FP16", "iPhone NE load"], body), ""]

    parts += ["## Latency: Mac against iPhone", "",
              "Median inference latency, FPS in brackets.", ""]
    body = []
    for s in SIZES:
        body.append([
            f"YOLO11{s}",
            f"{m[s]['cpu']['median_ms']:.1f} ms ({1000 / m[s]['cpu']['median_ms']:.0f})",
            f"{p[s]['cpu']['median_ms']:.1f} ms ({1000 / p[s]['cpu']['median_ms']:.0f})",
            f"{p[s]['cpu']['median_ms'] / m[s]['cpu']['median_ms']:.2f}x",
            f"{m[s]['ne']['median_ms']:.2f} ms ({1000 / m[s]['ne']['median_ms']:.0f})",
            f"{p[s]['ne']['median_ms']:.2f} ms ({1000 / p[s]['ne']['median_ms']:.0f})",
            f"{p[s]['ne']['median_ms'] / m[s]['ne']['median_ms']:.2f}x",
            f"{p[s]['cpu']['median_ms'] / p[s]['ne']['median_ms']:.1f}x",
        ])
    parts += [table(["Model", "Mac CPU", "iPhone CPU", "phone/Mac CPU",
                     "Mac CPU+NE", "iPhone CPU+NE", "phone/Mac NE",
                     "iPhone NE vs its CPU"], body), ""]

    parts += ["## Against a 30 FPS camera budget (33.3 ms per frame)", "",
              "p90 is the tail of the short run; the sustained column is 4,500 frames on",
              "the Neural Engine.", ""]
    body = []
    for s in SIZES:
        sustained = p[s].get("sustained")
        if sustained:
            note = (f"{sustained['median_ms']:.2f} ms ({1000 / sustained['median_ms']:.1f} FPS), "
                    f"p90 {sustained['p90_ms']:.2f}, thermal {sustained['thermal_state']}")
            if s == "m":
                # Measured on 14 September on iOS 26.5.2; its own short run of that
                # day is the only fair baseline for drift and is not machine-readable
                # any more (overwritten), so no drift is quoted here.
                note += f", {p[s]['sustained_os']}, not comparable to the row's short run"
            else:
                drift = sustained["median_ms"] / p[s]["ne"]["median_ms"] - 1.0
                note += f", {drift:+.1%} vs the short run"
        else:
            note = "-"
        body.append([
            f"YOLO11{s}",
            f"{p[s]['ne']['median_ms']:.2f} ms",
            f"{p[s]['ne']['p90_ms']:.2f} ms",
            f"{BUDGET_MS / p[s]['ne']['p90_ms']:.2f}x",
            "yes" if p[s]["cpu"]["median_ms"] < BUDGET_MS else "no",
            note,
        ])
    parts += [table(["Model", "iPhone NE median", "NE p90", "budget / p90",
                     "CPU-only at 30 FPS?", "Sustained NE run"], body), ""]

    OUT.write_text("\n".join(parts) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
